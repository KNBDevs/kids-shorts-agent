def arc(o, f0, a, b, dur, apex=0.25, r0=None, r1=None):
    for t in range(0, dur + 1, 2):
        u = t / dur
        u2 = u * u * (3 - 2 * u)
        p = a.lerp(b, u2)
        p.z += apex * 4 * u * (1 - u)
        K(o, 'location', f0 + t, tuple(p))
        if r0 is not None:
            K(o, 'rotation_euler', f0 + t, tuple(Vector(r0).lerp(Vector(r1), u2)))


